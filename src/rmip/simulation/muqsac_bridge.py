"""
rmip/simulation/muqsac_bridge.py
==================================
Future.md Part 2, Features 3 + 6 — RMIP <-> MUQ-SAC pipeline bridge.

Per KP's explicit direction, JSR/PFR simulation and reaction-flux analysis
do NOT get new native RMIP solver code. Instead RMIP:
  1. Builds a single-target ``.target`` file + ``.add`` addendum entry in the
     exact pipe-delimited / YAML formats ``src/MUQ-SAC/combustion_target_class.py``
     already parses (JSR/PFR/flux decks are generated by
     ``src/MUQ-SAC/make_input_file.py::create_input_file`` — see the
     Phase-6 additions there for all three solvers).
  2. Derives a ``target.opt`` from a KP-supplied base config (same schema as
     ``generate_target_opt.py`` produces), pointed at the new files.
  3. Shells out to ``src/MUQ-SAC/run_script.py <target.opt>`` as a subprocess
     — RMIP never imports MUQ-SAC modules directly (mirrors the D7 pattern
     used by ``MSOInterface``/``RMGInterface``).
  4. Parses the additive output files the Phase-6 decks write
     (``output/jsr_full.json``, ``output/pfr_full.json``, ``output/flux.json``
     — these do NOT change the pre-existing scalar ``.out`` contract that
     ``data_management.py`` consumes) into ``JSRResult``/``PFRResult``/``FluxResult``.
  5. Stores results in the RMIP DB (``simulation_runs`` for JSR/PFR,
     ``flux_runs`` for flux).

Composition handling
---------------------
``SimCondition.fuel``/``.oxidizer`` are Cantera set_equivalence_ratio-style
RATIO strings (e.g. ``"O2:1.0, N2:3.76"``), not literal mole fractions. This
module uses Cantera itself (already a hard RMIP dependency) to resolve the
exact mole-fraction dict at the requested φ, then splits it the way real
``.target`` files do: the O2 species -> ``Oxidizer``, fuel-string species ->
``Fuel``, everything else (N2, AR, CO2, …) -> ``Bath_gas``.

Testing note
------------
Steps 1–2 and 4–5 are fully unit-testable (no external binaries). Step 3
(the actual ``run_script.py`` invocation) requires a licensed Chemkin-Pro /
FlameMaster install plus the full MUQ-SAC uncertainty-analysis toolchain
(samap/jpdap binaries, SA tool scripts) and is exercised in tests only with
a mocked ``subprocess.run`` — see ``tests/test_phase6.py``.
"""

from __future__ import annotations

import json
import logging
import subprocess
import time
from pathlib import Path
from typing import Any, Dict, Optional

import yaml

from rmip.simulation.subprocess_util import resolve_timeout, sanitized_subprocess_env
from rmip.types import FluxResult, JSRResult, PFRResult, SimCondition

log = logging.getLogger("rmip.simulation.muqsac_bridge")

_UNITS = {"conc": "mol", "P": "atm", "T": "K", "observed": "s", "flow": ""}


class MuqsacBridge:
    """
    Bridge between RMIP and the ``src/MUQ-SAC`` pipeline for JSR/PFR
    simulation and reaction-flux analysis (Future.md pt. 3 + 6).

    Parameters
    ----------
    db_path : str
        RMIP SQLite database path.
    run_script_path : str
        Absolute path to ``src/MUQ-SAC/run_script.py``.
    """

    def __init__(self, db_path: str, run_script_path: str) -> None:
        self._db = db_path
        self._run_script = run_script_path

    # ------------------------------------------------------------------
    # 1-2. Build .target / .add / target.opt
    # ------------------------------------------------------------------

    def build_target_files(
        self,
        base_target_opt: str,
        mechanism_id: int,
        target_type: str,          # "JSR" | "PFR"
        solver: str,               # "cantera" | "CHEMKIN_PRO" | "FlameMaster"
        condition: SimCondition,
        work_dir: str,
        extra_add: Optional[Dict[str, Any]] = None,
        flux_analysis: bool = False,
        flux_element: str = "C",
        dataset_id: Optional[str] = None,
    ) -> Path:
        """
        Write ``<work_dir>/rmip.target``, ``<work_dir>/rmip.add``, and a
        derived ``<work_dir>/target.opt`` pointing at them.

        Returns the path to the derived ``target.opt``.
        """
        if target_type not in ("JSR", "PFR"):
            raise ValueError(f"target_type must be 'JSR' or 'PFR', got '{target_type}'")

        work = Path(work_dir)
        work.mkdir(parents=True, exist_ok=True)

        ds_id = dataset_id or f"rmip{int(time.time() * 1000) % 10**9}"

        fuel_dict, oxidizer_species, oxidizer_x, bath_gas = self._resolve_composition(
            mechanism_id, condition
        )

        target_line = self._build_target_line(
            ds_id, target_type, condition, fuel_dict, oxidizer_species,
            oxidizer_x, bath_gas,
        )
        target_path = work / "rmip.target"
        target_path.write_text(target_line + "\n")

        add_entry: Dict[str, Any] = {
            "solver": solver,
            "species": (extra_add or {}).get("species") or next(iter(fuel_dict)),
            "residenceTime": (extra_add or {}).get("residenceTime", 1.0),
            "MaxSimulationTime": (extra_add or {}).get("MaxSimulationTime", 10.0),
            "flux_analysis": flux_analysis,
            "flux_element": flux_element,
        }
        if target_type == "PFR":
            add_entry.update({
                "pfr_length":   (extra_add or {}).get("pfr_length", 0.1),
                "pfr_diameter": (extra_add or {}).get("pfr_diameter", 0.02),
                "pfr_mdot":     (extra_add or {}).get("pfr_mdot", 1e-3),
                "pfr_n_points": (extra_add or {}).get("pfr_n_points", 200),
            })
        if extra_add:
            add_entry.update({k: v for k, v in extra_add.items() if k not in add_entry})

        add_path = work / "rmip.add"
        with open(add_path, "w") as fh:
            yaml.safe_dump({ds_id: add_entry}, fh, default_flow_style=False)

        with open(base_target_opt) as fh:
            cfg = yaml.safe_load(fh)
        cfg.setdefault("Locations", {})
        cfg["Locations"]["targets"] = str(target_path)
        cfg["Locations"]["addendum"] = str(add_path)
        cfg.setdefault("Counts", {})
        cfg["Counts"]["targets_count"] = 1

        target_opt_path = work / "target.opt"
        with open(target_opt_path, "w") as fh:
            yaml.safe_dump(cfg, fh, default_flow_style=False)

        log.info("Built RMIP-driven target.opt for mechanism_id=%d, %s/%s -> %s",
                  mechanism_id, target_type, solver, target_opt_path)
        return target_opt_path

    def _resolve_composition(self, mechanism_id: int, condition: SimCondition):
        """
        Resolve (fuel_dict, oxidizer_species, oxidizer_x, bath_gas_dict) mole
        fractions at condition.phi using Cantera, splitting the mixture the
        way real .target files do (O2 alone -> Oxidizer, rest -> Bath_gas).
        """
        from rmip.simulation.base import MechanismLoader

        gas = MechanismLoader(self._db).load(mechanism_id)
        gas.set_equivalence_ratio(condition.phi, fuel=condition.fuel,
                                   oxidizer=condition.oxidizer)
        mole_fracs = gas.mole_fraction_dict()

        fuel_species = {s.split(":")[0].strip() for s in condition.fuel.split(",")}
        fuel_dict = {sp: x for sp, x in mole_fracs.items() if sp in fuel_species and x > 0}

        oxidizer_species = "O2"
        oxidizer_x = mole_fracs.get("O2", 0.0)

        bath_gas = {
            sp: x for sp, x in mole_fracs.items()
            if sp not in fuel_dict and sp != oxidizer_species and x > 0
        }
        return fuel_dict, oxidizer_species, oxidizer_x, bath_gas

    @staticmethod
    def _build_target_line(
        ds_id: str, target_type: str, condition: SimCondition,
        fuel_dict: Dict[str, float], oxidizer_species: str, oxidizer_x: float,
        bath_gas: Dict[str, float],
    ) -> str:
        """
        Build one pipe-delimited .target line matching
        combustion_target_class.combustion_target's parser exactly.
        """
        if len(fuel_dict) == 1:
            fuel_type = "Mono"
            sp, x = next(iter(fuel_dict.items()))
            fuel_field = f"Fuel -- x->{sp}={x}"
        else:
            fuel_type = "Multi"
            keys = {chr(97 + i): sp for i, sp in enumerate(fuel_dict)}
            vals = {chr(97 + i): x for i, (sp, x) in enumerate(fuel_dict.items())}
            fuel_field = f"Fuel -- x->{keys}={vals}"

        bath_keys = {chr(97 + i): sp for i, sp in enumerate(bath_gas)}
        bath_vals = {chr(97 + i): x for i, x in enumerate(bath_gas.values())}

        fields = [
            "1",
            ds_id,
            f" target -- {target_type}",
            " simulation -- ",
            " measurnment_type -- ",
            "Ignition_mode -- ",
            " Flame_type -- ",
            f" Reactor_type -- {target_type}",
            f" Fuel_type -- {fuel_type}",
            f" {fuel_field}",
            f" Oxidizer -- x->{oxidizer_species} = {oxidizer_x}",
            f" Bath_gas -- x->{bath_keys}={bath_vals}",
            f"T -- {condition.T_K}",
            f" P -- {condition.P_atm}",
            " flow_rate -- ",
            f"Phi -- {condition.phi}",
            " observed -- 0.0",
            " obs_unit --unitless ",
            " deviation -- 1.0",
            "data_weight -- 1",
            f"units -- {_UNITS}",
        ]
        return "\t|".join(fields)

    # ------------------------------------------------------------------
    # 3. Run
    # ------------------------------------------------------------------

    def run(
        self,
        target_opt_path: Path,
        timeout: Optional[float] = None,
    ) -> subprocess.CompletedProcess:
        """
        Invoke ``src/MUQ-SAC/run_script.py <target_opt_path>`` as a subprocess.

        RMIP never imports MUQ-SAC modules (D7-style contract). CWD is set to
        the target.opt's parent directory so the pipeline's relative
        ``output/*`` paths land alongside the generated .target/.add files.
        """
        work_dir = Path(target_opt_path).parent
        cmd = ["python3", self._run_script, str(target_opt_path)]
        log.info("Running MUQ-SAC pipeline: %s (cwd=%s)", " ".join(cmd), work_dir)
        # M18b: finite default timeout (no more unbounded None) + sanitized env
        # so a foreign LD_LIBRARY_PATH (e.g. ANSYS libstdc++) can't break the
        # pipeline's Cantera/solver subprocesses.
        return subprocess.run(
            cmd, cwd=str(work_dir), capture_output=True, text=True,
            timeout=resolve_timeout(timeout), env=sanitized_subprocess_env(),
        )

    # ------------------------------------------------------------------
    # 4. Parse output
    # ------------------------------------------------------------------

    def parse_jsr_output(
        self, work_dir: str, mechanism_id: int, solver: str, condition: SimCondition,
    ) -> JSRResult:
        path = Path(work_dir) / "output" / "jsr_full.json"
        if not path.exists():
            return JSRResult(
                condition=condition, mechanism_id=mechanism_id, solver=solver,
                residence_time_s=0.0, species_mole_fractions={}, converged=False,
                error_msg=f"Output file not found: {path}",
            )
        with open(path) as fh:
            data = json.load(fh)
        return JSRResult(
            condition=condition, mechanism_id=mechanism_id, solver=solver,
            residence_time_s=data.get("residence_time_s", 0.0),
            species_mole_fractions=data.get("species_mole_fractions", {}),
            converged=data.get("converged", False),
            error_msg=data.get("error_msg"),
        )

    def parse_pfr_output(
        self, work_dir: str, mechanism_id: int, solver: str, condition: SimCondition,
    ) -> PFRResult:
        path = Path(work_dir) / "output" / "pfr_full.json"
        if not path.exists():
            return PFRResult(
                condition=condition, mechanism_id=mechanism_id, solver=solver,
                length_m=0.0, residence_time_s=None, species_mole_fractions={},
                converged=False, error_msg=f"Output file not found: {path}",
            )
        with open(path) as fh:
            data = json.load(fh)
        return PFRResult(
            condition=condition, mechanism_id=mechanism_id, solver=solver,
            length_m=data.get("length_m", 0.0),
            residence_time_s=data.get("residence_time_s"),
            species_mole_fractions=data.get("species_mole_fractions", {}),
            axial_profile=data.get("axial_profile"),
            converged=data.get("converged", False),
            error_msg=data.get("error_msg"),
        )

    def parse_flux_output(
        self, work_dir: str, mechanism_id: int, solver: str, condition: SimCondition,
        element: str = "C",
    ) -> FluxResult:
        path = Path(work_dir) / "output" / "flux.json"
        if not path.exists():
            return FluxResult(
                mechanism_id=mechanism_id, condition=condition, solver=solver,
                element=element, rop_by_reaction={}, element_flux=[],
                converged=False, error_msg=f"Output file not found: {path}",
            )
        with open(path) as fh:
            data = json.load(fh)
        rop = data.get("rop", {})
        edges = _sankey_edges_from_rop(rop, data.get("element", element))
        return FluxResult(
            mechanism_id=mechanism_id, condition=condition, solver=solver,
            element=data.get("element", element),
            rop_by_reaction=rop, element_flux=edges, converged=True,
        )

    # ------------------------------------------------------------------
    # 5. Store
    # ------------------------------------------------------------------

    def store_reactor_result(self, result, tracked_species: Optional[str] = None) -> int:
        """
        Store a JSRResult or PFRResult into simulation_runs.

        ``extra_json`` always carries the full species-composition payload
        (the scalar ``result`` column can't). If ``tracked_species`` is given
        (the single calibration-target species, e.g. ``target.add["species"]``
        from the MUQ-SAC addendum), its mole fraction is ALSO written to the
        scalar ``result`` column for parity with IDT/LFS rows; otherwise
        ``result`` is left NULL rather than guessing which species matters.
        """
        import sqlite3
        from rmip.database.schema import init_db
        from rmip.database.schema_phase3 import insert_simulation_run

        sim_type = "JSR" if isinstance(result, JSRResult) else "PFR"
        conn = init_db(self._db)
        fuel_name = result.condition.fuel.split(":")[0]
        scalar_result = (
            result.species_mole_fractions.get(tracked_species)
            if tracked_species else None
        )
        extra = json.dumps({
            "species_mole_fractions": result.species_mole_fractions,
            **({"axial_profile": result.axial_profile}
               if sim_type == "PFR" and result.axial_profile else {}),
        })
        return insert_simulation_run(
            conn, mechanism_id=result.mechanism_id, sim_type=sim_type,
            T_K=result.condition.T_K, P_atm=result.condition.P_atm,
            phi=result.condition.phi, fuel_name=fuel_name,
            fuel_composition=result.condition.fuel,
            oxidizer_composition=result.condition.oxidizer,
            result=scalar_result, converged=result.converged,
            cpu_time_s=result.cpu_time_s, error_msg=result.error_msg,
            extra_json=extra,
        )

    def store_flux_result(self, result: FluxResult) -> int:
        from rmip.database.schema import init_db
        from rmip.database.schema_phase6 import insert_flux_run

        conn = init_db(self._db)
        return insert_flux_run(
            conn, mechanism_id=result.mechanism_id, solver=result.solver,
            T_K=result.condition.T_K, P_atm=result.condition.P_atm,
            phi=result.condition.phi, fuel_composition=result.condition.fuel,
            element=result.element, rop_by_reaction=result.rop_by_reaction,
            element_flux=result.element_flux, converged=result.converged,
            cpu_time_s=result.cpu_time_s, error_msg=result.error_msg,
        )


def _sankey_edges_from_rop(rop: Dict[str, float], element: str) -> list:
    """
    Build simple Sankey-ready edges from a {reaction_equation: rop} dict by
    splitting each equation on '<=>'/'=>'/'=' into reactant/product species
    strings. Coefficients and third bodies are not parsed out — this is a
    lightweight structural view, not a full atom-mapped flux analysis.
    """
    edges = []
    for eq, value in rop.items():
        for sep in ("<=>", "=>", "="):
            if sep in eq:
                lhs, rhs = eq.split(sep, 1)
                break
        else:
            continue
        reactants = [s.strip() for s in lhs.replace("(+M)", "").split("+")]
        products = [s.strip() for s in rhs.replace("(+M)", "").split("+")]
        for r in reactants:
            for p in products:
                edges.append({"source": r, "target": p, "reaction": eq, "value": value})
    return edges
