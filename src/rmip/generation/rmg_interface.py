# ─────────────────────────────────────────────────────────────────────────────
# RMG input.py template
# ─────────────────────────────────────────────────────────────────────────────

_RMG_INPUT_TEMPLATE = """\
# RMG input file — auto-generated by RMIP RMGInterface
# Fuel: {fuel_name} ({fuel_smiles})

database(
    thermoLibraries=['BurkeH2O2', 'primaryThermoLibrary', 'CombSurfinit'],
    reactionLibraries=[],
    seedMechanisms=['GRI-Mech3.0-N'],
    kineticsDepositories='default',
    kineticsFamilies='default',
    kineticsEstimator='rate rules',
)

species(
    label='{fuel_name}',
    reactive=True,
    structure=SMILES('{fuel_smiles}'),
)

species(
    label='O2',
    reactive=True,
    structure=SMILES('[O][O]'),
)

species(
    label='N2',
    reactive=False,
    structure=SMILES('N#N'),
)

simpleReactor(
    temperature=({T_lo}, {T_hi}, 'K'),
    pressure=({P_atm}, 'atm'),
    initialMoleFractions={{
        '{fuel_name}': {fuel_mf},
        'O2':  {O2_mf},
        'N2':  {N2_mf},
    }},
    terminationConversion={{'{fuel_name}': 0.99}},
    terminationTime=(1.0, 's'),
)

simulator(atol=1e-16, rtol=1e-8)

model(
    toleranceMoveToCore=0.1,
    toleranceInterruptSimulation=1.0,
    maximumEdgeSpecies=100000,
)

options(
    units='si',
    generateOutputHTML=False,
    generatePlots=False,
    saveEdgeSpecies=False,
    saveSimulationProfiles=False,
)
"""

# ─────────────────────────────────────────────────────────────────────────────
# Result types
# ─────────────────────────────────────────────────────────────────────────────

class MissingPathwaysReport:
    """Summary of what is present in the RMG mechanism but missing from the base mechanism."""

    def __init__(
        self,
        base_mech_id: int,
        rmg_mech_id:  int,
        missing_inchi_keys:     List[str],
        missing_canonical_keys: List[str],
    ) -> None:
        self.base_mech_id          = base_mech_id
        self.rmg_mech_id           = rmg_mech_id
        self.missing_inchi_keys    = missing_inchi_keys
        self.missing_canonical_keys = missing_canonical_keys

    @property
    def n_missing_species(self) -> int:
        return len(self.missing_inchi_keys)

    @property
    def n_missing_reactions(self) -> int:
        return len(self.missing_canonical_keys)

    def __repr__(self) -> str:
        return (
            f"MissingPathwaysReport(base={self.base_mech_id}, rmg={self.rmg_mech_id},"
            f" missing_species={self.n_missing_species},"
            f" missing_reactions={self.n_missing_reactions})"
        )

    def to_dict(self) -> dict:
        return {
            "base_mech_id":            self.base_mech_id,
            "rmg_mech_id":             self.rmg_mech_id,
            "n_missing_species":       self.n_missing_species,
            "n_missing_reactions":     self.n_missing_reactions,
            "missing_inchi_keys":      self.missing_inchi_keys,
            "missing_canonical_keys":  self.missing_canonical_keys,
        }


# ─────────────────────────────────────────────────────────────────────────────
# RMGInterface
# ─────────────────────────────────────────────────────────────────────────────

class RMGInterface:
    """
    Module 5 — Targeted Pathway Completion via RMG-Py.

    Parameters
    ----------
    db_path : str | Path — RMIP SQLite database
    """

    def __init__(self, db_path: str | Path) -> None:
        self._db_path = str(db_path)

    # ─────────────────────────────────────────────────────────────────────────
    # Step 1: Generate via RMG subprocess
    # ─────────────────────────────────────────────────────────────────────────

    def generate(
        self,
        fuel_smiles:      str,
        fuel_name:        str,
        fuel_mole_frac:   float = 0.0585,   # stoichiometric in air
        T_lo_K:           float = 800.0,
        T_hi_K:           float = 1600.0,
        P_atm:            float = 1.0,
        output_dir:       str = "rmg_run",
        rmg_path:         Optional[str] = None,
        python_exe:       str = sys.executable,
        timeout_s:        Optional[float] = 3600.0,
    ) -> Path:
        """
        Write an RMG input.py and call RMG as a subprocess.

        Parameters
        ----------
        fuel_smiles     : str   — RDKit-canonical SMILES for the fuel
        fuel_name       : str   — Cantera-style name (e.g. "NC7H16")
        fuel_mole_frac  : float — fuel mole fraction (default: stoich in air)
        T_lo_K, T_hi_K : float — temperature range for reactor
        P_atm           : float — pressure (atm)
        output_dir      : str   — directory for RMG output
        rmg_path        : str   — path to rmg.py (if not on PATH)
        python_exe      : str   — Python interpreter
        timeout_s       : float — subprocess timeout

        Returns
        -------
        Path to RMG output directory
        """
        out_dir = Path(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)

        # Compute air composition
        O2_mf  = fuel_mole_frac * (1 - fuel_mole_frac) * 0.21 / fuel_mole_frac
        N2_mf  = 1.0 - fuel_mole_frac - O2_mf

        inp_content = _RMG_INPUT_TEMPLATE.format(
            fuel_name=fuel_name,
            fuel_smiles=fuel_smiles,
            T_lo=T_lo_K,
            T_hi=T_hi_K,
            P_atm=P_atm,
            fuel_mf=round(fuel_mole_frac, 6),
            O2_mf=round(O2_mf, 6),
            N2_mf=round(N2_mf, 6),
        )

        inp_path = out_dir / "input.py"
        inp_path.write_text(inp_content)
        log.info("RMG input.py written: %s", inp_path)

        # Determine rmg command
        if rmg_path:
            cmd = [python_exe, str(rmg_path), str(inp_path)]
        else:
            # Try 'rmg.py' on PATH
            cmd = ["rmg.py", str(inp_path)]

        log.info("Launching RMG: %s", " ".join(cmd))
        try:
            from rmip.simulation.subprocess_util import rmg_subprocess_env
            proc = subprocess.run(
                cmd,
                cwd=str(out_dir),
                capture_output=True,
                text=True,
                timeout=timeout_s,
                env=rmg_subprocess_env(python_exe),
            )
        except FileNotFoundError:
            raise RuntimeError(
                "RMG executable not found.  Supply rmg_path or add rmg.py to PATH."
            )
        except subprocess.TimeoutExpired:
            raise RuntimeError(f"RMG timed out after {timeout_s} s")

        if proc.returncode != 0:
            log.error("RMG failed (exit %d):\n%s", proc.returncode, proc.stderr[-3000:])
            raise RuntimeError(
                f"RMG exited with code {proc.returncode}.\n"
                f"Stderr (last 3000 chars):\n{proc.stderr[-3000:]}"
            )

        log.info("RMG completed successfully.  Output in %s", out_dir)
        return out_dir

    # ─────────────────────────────────────────────────────────────────────────
    # Step 2: Load RMG output into RMIP DB
    # ─────────────────────────────────────────────────────────────────────────

    def load_rmg_output(
        self,
        chemkin_path: str,
        thermo_path:  Optional[str] = None,
        smiles_csv:   Optional[str] = None,
        db_name:      str = "RMG_mechanism",
    ) -> int:
        """
        Parse RMG CHEMKIN output and load into RMIP DB.

        Parameters
        ----------
        chemkin_path : str — path to RMG chem.inp (mechanism)
        thermo_path  : str | None — path to therm.dat (if separate)
        smiles_csv   : str | None — glossary CSV with RMG species SMILES
                        (RMG embeds SMILES in comments; if None, InChI keys
                        are set to the species name as a fallback)
        db_name      : str — name for the mechanism entry in RMIP DB

        Returns
        -------
        int: mechanism_id of the loaded RMG mechanism
        """
        from rmip.core.parser import MechanismParser
        from rmip.config import RMIPConfig

        log.info("Loading RMG output: %s", chemkin_path)
        parser = MechanismParser(RMIPConfig(db_path=self._db_path))
        mech_id = parser.parse(
            mech_path=chemkin_path,
            thermo_path=thermo_path,
            glossary_path=smiles_csv,
            name=db_name,
            description=f"RMG-generated mechanism from {Path(chemkin_path).name}",
        )
        log.info("RMG mechanism loaded: DB id=%d", mech_id)
        return mech_id

    # ─────────────────────────────────────────────────────────────────────────
    # Step 3: Find missing chemistry
    # ─────────────────────────────────────────────────────────────────────────

    def find_missing_species(
        self,
        base_mech_id: int,
        rmg_mech_id:  int,
    ) -> List[str]:
        """
        Return inchi_keys present in the RMG mechanism but NOT in the base mechanism.

        Parameters
        ----------
        base_mech_id : int — the RMIP mechanism to extend
        rmg_mech_id  : int — the RMG-generated mechanism (already in DB)

        Returns
        -------
        list[str] — inchi_keys of missing species
        """
        with sqlite3.connect(self._db_path) as conn:
            base_keys = self._get_species_keys(conn, base_mech_id)
            rmg_keys  = self._get_species_keys(conn, rmg_mech_id)

        missing = sorted(rmg_keys - base_keys)
        log.info(
            "find_missing_species: base=%d rmg=%d → %d missing species",
            base_mech_id, rmg_mech_id, len(missing),
        )
        return missing

    def find_missing_reactions(
        self,
        base_mech_id: int,
        rmg_mech_id:  int,
    ) -> List[str]:
        """
        Return canonical_keys present in the RMG mechanism but NOT in the base mechanism.
        """
        with sqlite3.connect(self._db_path) as conn:
            base_keys = self._get_reaction_keys(conn, base_mech_id)
            rmg_keys  = self._get_reaction_keys(conn, rmg_mech_id)

        missing = sorted(rmg_keys - base_keys)
        log.info(
            "find_missing_reactions: base=%d rmg=%d → %d missing reactions",
            base_mech_id, rmg_mech_id, len(missing),
        )
        return missing

    def find_missing_pathways(
        self,
        base_mech_id: int,
        rmg_mech_id:  int,
    ) -> MissingPathwaysReport:
        """
        Combined species + reaction gap report.
        """
        missing_sp  = self.find_missing_species(base_mech_id, rmg_mech_id)
        missing_rxn = self.find_missing_reactions(base_mech_id, rmg_mech_id)
        return MissingPathwaysReport(
            base_mech_id=base_mech_id,
            rmg_mech_id=rmg_mech_id,
            missing_inchi_keys=missing_sp,
            missing_canonical_keys=missing_rxn,
        )

    # ─────────────────────────────────────────────────────────────────────────
    # Step 4: Append missing pathways to base mechanism
    # ─────────────────────────────────────────────────────────────────────────

    def append_to_mechanism(
        self,
        base_mech_id:       int,
        rmg_mech_id:        int,
        missing_inchi_keys: Optional[List[str]] = None,
        missing_canonical_keys: Optional[List[str]] = None,
        new_name:           Optional[str] = None,
    ) -> int:
        """
        Copy missing species (and optionally reactions) from the RMG mechanism
        into the base mechanism.

        By default all missing species and their reactions are appended.
        Pass explicit lists to restrict what is copied.

        Parameters
        ----------
        base_mech_id            : int
        rmg_mech_id             : int
        missing_inchi_keys      : list[str] | None
            If None → computed automatically via find_missing_species().
        missing_canonical_keys  : list[str] | None
            If None → computed automatically via find_missing_reactions().
        new_name                : str | None
            If provided, a *new* mechanism is created (clone of base + RMG
            additions) with this name instead of mutating base in-place.
            Recommended when you want to compare before and after.

        Returns
        -------
        int — mechanism_id that was updated (base_mech_id or new clone id)
        """
        if missing_inchi_keys is None:
            missing_inchi_keys = self.find_missing_species(base_mech_id, rmg_mech_id)
        if missing_canonical_keys is None:
            missing_canonical_keys = self.find_missing_reactions(base_mech_id, rmg_mech_id)

        if not missing_inchi_keys and not missing_canonical_keys:
            log.info("No missing pathways to append — base mechanism is complete.")
            return base_mech_id

        with sqlite3.connect(self._db_path) as conn:
            conn.row_factory = sqlite3.Row

            # Optionally clone the base mechanism first
            target_mech_id = self._clone_if_needed(conn, base_mech_id, new_name)

            # ── Copy missing species ──────────────────────────────────────
            n_sp_added = 0
            for ik in missing_inchi_keys:
                rmg_sp_rows = conn.execute(
                    "SELECT * FROM species WHERE mechanism_id=? AND inchi_key=?",
                    (rmg_mech_id, ik),
                ).fetchall()
                for sp in rmg_sp_rows:
                    sp_dict = dict(sp)
                    sp_dict.pop("id")
                    sp_dict["mechanism_id"] = target_mech_id
                    sp_dict["thermo_comment"] = (
                        (sp_dict.get("thermo_comment") or "") +
                        f" [Added from RMG mech {rmg_mech_id}]"
                    ).strip()
                    cols = list(sp_dict.keys())
                    conn.execute(
                        f"INSERT INTO species ({','.join(cols)}) VALUES ({','.join(['?']*len(cols))})",
                        [sp_dict[c] for c in cols],
                    )
                    n_sp_added += 1

            # Reload species mapping for stoichiometry
            sp_ik_to_id = {
                row["inchi_key"]: row["id"]
                for row in conn.execute(
                    "SELECT id, inchi_key FROM species WHERE mechanism_id=?",
                    (target_mech_id,),
                ).fetchall()
            }

            # ── Copy missing reactions ────────────────────────────────────
            n_rxn_added = 0
            for ck in missing_canonical_keys:
                rmg_rxn_rows = conn.execute(
                    "SELECT * FROM reactions WHERE mechanism_id=? AND canonical_key=?",
                    (rmg_mech_id, ck),
                ).fetchall()
                for rxn in rmg_rxn_rows:
                    rxn_dict = dict(rxn)
                    old_rxn_id = rxn_dict.pop("id")
                    rxn_dict["mechanism_id"] = target_mech_id
                    rxn_dict["rmg_comment"] = (
                        (rxn_dict.get("rmg_comment") or "") +
                        f" [Added from RMG mech {rmg_mech_id}]"
                    ).strip()
                    cols = list(rxn_dict.keys())
                    cur = conn.execute(
                        f"INSERT INTO reactions ({','.join(cols)}) VALUES ({','.join(['?']*len(cols))})",
                        [rxn_dict[c] for c in cols],
                    )
                    new_rxn_id = cur.lastrowid
                    n_rxn_added += 1

                    # Copy stoichiometry
                    stoich = conn.execute(
                        """
                        SELECT s.stoich_coeff, s.role, sp.inchi_key
                          FROM stoichiometry s
                          JOIN species sp ON sp.id = s.species_id
                         WHERE s.reaction_id = ?
                        """,
                        (old_rxn_id,),
                    ).fetchall()
                    for srow in stoich:
                        tgt_sp_id = sp_ik_to_id.get(srow["inchi_key"])
                        if tgt_sp_id is None:
                            log.debug(
                                "Stoich: inchi_key=%s not in target mechanism %d",
                                srow["inchi_key"], target_mech_id,
                            )
                            continue
                        conn.execute(
                            "INSERT INTO stoichiometry (reaction_id, species_id, stoich_coeff, role) VALUES (?,?,?,?)",
                            (new_rxn_id, tgt_sp_id, srow["stoich_coeff"], srow["role"]),
                        )

            # Update species / reaction counts
            sp_count  = conn.execute(
                "SELECT COUNT(*) FROM species WHERE mechanism_id=?", (target_mech_id,)
            ).fetchone()[0]
            rxn_count = conn.execute(
                "SELECT COUNT(*) FROM reactions WHERE mechanism_id=?", (target_mech_id,)
            ).fetchone()[0]
            conn.execute(
                "UPDATE mechanisms SET n_species=?, n_reactions=? WHERE id=?",
                (sp_count, rxn_count, target_mech_id),
            )
            conn.commit()

        log.info(
            "append_to_mechanism: target=%d  added %d species, %d reactions",
            target_mech_id, n_sp_added, n_rxn_added,
        )
        return target_mech_id

    # ─────────────────────────────────────────────────────────────────────────
    # Internal helpers
    # ─────────────────────────────────────────────────────────────────────────

    def _get_species_keys(self, conn: sqlite3.Connection, mech_id: int) -> Set[str]:
        rows = conn.execute(
            "SELECT inchi_key FROM species WHERE mechanism_id=? AND inchi_key IS NOT NULL",
            (mech_id,),
        ).fetchall()
        return {row[0] for row in rows}

    def _get_reaction_keys(self, conn: sqlite3.Connection, mech_id: int) -> Set[str]:
        rows = conn.execute(
            "SELECT canonical_key FROM reactions WHERE mechanism_id=? AND canonical_key IS NOT NULL",
            (mech_id,),
        ).fetchall()
        return {row[0] for row in rows}

    def _clone_if_needed(
        self,
        conn: sqlite3.Connection,
        base_mech_id: int,
        new_name: Optional[str],
    ) -> int:
        """Return base_mech_id unchanged, or create a clone with new_name."""
        if new_name is None:
            return base_mech_id

        conn.row_factory = sqlite3.Row
        base_row = conn.execute(
            "SELECT * FROM mechanisms WHERE id=?", (base_mech_id,)
        ).fetchone()
        if base_row is None:
            raise ValueError(f"Mechanism id={base_mech_id} not found")

        ts = datetime.now(timezone.utc).isoformat()
        cur = conn.execute(
            """
            INSERT INTO mechanisms
                (name, format, filepath, description, n_species, n_reactions, loaded_at, metadata_json)
            VALUES (?,?,?,?,?,?,?,?)
            """,
            (
                new_name,
                base_row["format"],
                base_row["filepath"],
                f"Clone of mech {base_mech_id} + RMG additions",
                base_row["n_species"],
                base_row["n_reactions"],
                ts,
                base_row["metadata_json"],
            ),
        )
        new_id = cur.lastrowid

        # Clone species
        for sp in conn.execute("SELECT * FROM species WHERE mechanism_id=?", (base_mech_id,)):
            d = dict(sp)
            d.pop("id")
            d["mechanism_id"] = new_id
            cols = list(d.keys())
            conn.execute(
                f"INSERT INTO species ({','.join(cols)}) VALUES ({','.join(['?']*len(cols))})",
                [d[c] for c in cols],
            )

        # Clone reactions + stoichiometry
        old_new_rxn: Dict[int, int] = {}
        for rxn in conn.execute("SELECT * FROM reactions WHERE mechanism_id=?", (base_mech_id,)):
            d = dict(rxn)
            old_id = d.pop("id")
            d["mechanism_id"] = new_id
            cols = list(d.keys())
            cur2 = conn.execute(
                f"INSERT INTO reactions ({','.join(cols)}) VALUES ({','.join(['?']*len(cols))})",
                [d[c] for c in cols],
            )
            old_new_rxn[old_id] = cur2.lastrowid

        for srow in conn.execute(
            """
            SELECT s.*
              FROM stoichiometry s
              JOIN reactions r ON r.id = s.reaction_id
             WHERE r.mechanism_id = ?
            """,
            (base_mech_id,),
        ):
            new_rxn_id = old_new_rxn.get(srow["reaction_id"])
            if new_rxn_id:
                conn.execute(
                    "INSERT INTO stoichiometry (reaction_id, species_id, stoich_coeff, role) VALUES (?,?,?,?)",
                    (new_rxn_id, srow["species_id"], srow["stoich_coeff"], srow["role"]),
                )

        conn.commit()
        log.info("Created clone mechanism id=%d ('%s')", new_id, new_name)
        return new_id
