"""
rmip/generation/rmg_interface.py
=================================
Module 5: Targeted Pathway Completion via RMG-Py

What it does
------------
1. **generate()** — writes an RMG input.py for a given fuel (SMILES) and
   calls RMG as a subprocess.  RMG generates a CHEMKIN mechanism.
2. **load_rmg_output()** — parses the RMG CHEMKIN output directly (no subprocess)
   if the user has already run RMG separately.
3. **find_missing_species()** — compares the RMIP DB mechanism against the RMG
   mechanism by inchi_key; returns species present in RMG but absent from RMIP.
4. **find_missing_reactions()** — same, by canonical_key.
5. **append_to_mechanism()** — writes missing species and their reactions into
   the RMIP DB, extending the specified mechanism.  Thermo is copied from the
   RMG species data.

Design notes
------------
- RMG is invoked as a subprocess; RMG-Py is not imported directly.
  This keeps the RMIP package independent of RMG-Py installation.
- If the user has RMG output already (a CHEMKIN pair), they can skip step 1.
- InChI keys for RMG species are obtained by calling the ``cantera-tools``
  route: convert RMG CHEMKIN → Cantera YAML → then use ``cantera_reader.py``
  (which calls RDKit internally on the glossary).
  Alternatively, RMIP can run rdkit directly on the RMG species SMILES string
  (RMG embeds SMILES in the CHEMKIN file comments).
- Transport data: NOT copied even from RMG (design decision D6).

Usage
-----
>>> from rmip.generation.rmg_interface import RMGInterface
>>> rmg = RMGInterface("project.db")
>>> # Option A: generate via RMG
>>> rmg.generate(
...     fuel_smiles="CCCCCCC",
...     fuel_name="NC7H16",
...     fuel_composition={"NC7H16": 1},
...     output_dir="rmg_run/",
...     rmg_path="/path/to/rmg.py",
... )
>>> # Option B: load existing RMG output
>>> rmg.load_rmg_output(
...     chemkin_path="rmg_run/chemkin/chem.inp",
...     thermo_path="rmg_run/chemkin/therm.dat",
...     smiles_csv="rmg_run/species_smiles.csv",     # optional; may be None
...     db_name="RMG_NC7H16",
... )
>>> # Find what is missing in mechanism 1 relative to RMG
>>> missing = rmg.find_missing_species(base_mech_id=1, rmg_mech_id=2)
>>> print(missing)
>>> # Append to mechanism 1
>>> rmg.append_to_mechanism(
...     base_mech_id=1,
...     rmg_mech_id=2,
...     missing_inchi_keys=missing,
... )
"""

