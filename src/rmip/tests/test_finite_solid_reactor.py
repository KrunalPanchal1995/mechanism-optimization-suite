"""
W5a — FiniteSolidReactor acceptance tests (P6/P7/P8/P9).

Fixture: fixtures/char_oxidation.yaml (generated by _make_char_fixture.py) —
gas (O2/CO/CO2/N2) + bulk C(b) + surface {(s), O(s)} char-oxidation mechanism.

The acceptance criteria from W5_surface_heterogeneous.md:
- total element mass conserved to 1e-8 over full burnout (no artificial
  mass — P7),
- sum(theta) stays 1 (P8),
- isothermal and non-isothermal both integrate to completion (P9),
- bulk mass monotonically depletes (P6).
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pytest

SRC = Path(__file__).resolve().parents[2]
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from rmip.simulation.finite_solid_reactor import (      # noqa: E402
    FiniteSolidReactor, MassBalanceError, constant_area, shrinking_core_area)

MECH = str(Path(__file__).parent / "fixtures" / "char_oxidation.yaml")

# Small particle + small gas volume => fast burnout, fast tests.
FAST = dict(T0=1600.0, bulk_mass_kg=1.0e-6, gas_volume_m3=1.0e-4)


@pytest.fixture(scope="module")
def burnout_result():
    """One full non-isothermal burnout, shared across tests."""
    reactor = FiniteSolidReactor(MECH, **FAST)
    return reactor.run(t_end=200.0)


# ---------------------------------------------------------------------------
# P6 — bulk mass is a real, depleting state
# ---------------------------------------------------------------------------
def test_bulk_depletes_monotonically_to_burnout(burnout_result):
    res = burnout_result
    assert res.burned_out, "particle should fully burn out within t_end"
    assert res.burnout_time is not None
    m = res.m_bulk
    assert m[0] == pytest.approx(FAST["bulk_mass_kg"])
    # Monotone non-increasing (oxidation only consumes the solid).
    assert np.all(np.diff(m) <= 1.0e-15)
    # Burnout means essentially nothing left.
    assert m[-1] <= 1.0e-3 * m[0]


def test_area_follows_shrinking_core(burnout_result):
    res = burnout_result
    expected = res.area[0] * (res.m_bulk / res.m_bulk[0]) ** (2.0 / 3.0)
    np.testing.assert_allclose(res.area, expected, rtol=1e-12)


# ---------------------------------------------------------------------------
# P7 — no artificial mass: element totals conserved through burnout
# ---------------------------------------------------------------------------
def test_element_mass_conserved_to_1e8(burnout_result):
    res = burnout_result
    assert res.audit["max_element_drift_rel"] < 1.0e-8
    # And nothing was silently clipped into existence.
    assert res.audit["clipped_mass_kg"] < 1.0e-12


def test_carbon_ends_up_in_gas(burnout_result):
    """The bulk carbon must reappear as gas-phase CO/CO2 carbon."""
    res = burnout_result
    i_co = res.gas_species.index("CO")
    i_co2 = res.gas_species.index("CO2")
    # kg of C in gas at the end (12.011/28.010 of CO, 12.011/44.009 of CO2)
    m_c_gas = (res.gas_mass[-1, i_co] * 12.011 / 28.010
               + res.gas_mass[-1, i_co2] * 12.011 / 44.009)
    m_c_lost = res.m_bulk[0] - res.m_bulk[-1]        # all bulk is pure C
    assert m_c_gas == pytest.approx(m_c_lost, rel=1e-6)


# ---------------------------------------------------------------------------
# P8 — coverage sum is exactly 1; site total conserved
# ---------------------------------------------------------------------------
def test_coverage_sum_is_one(burnout_result):
    res = burnout_result
    sums = res.coverages.sum(axis=1)
    np.testing.assert_allclose(sums, 1.0, atol=1e-12)


def test_site_total_conserved(burnout_result):
    assert burnout_result.audit["max_site_drift_rel"] < 1.0e-6


# ---------------------------------------------------------------------------
# P9 — both energy modes integrate to completion
# ---------------------------------------------------------------------------
def test_isothermal_completes():
    reactor = FiniteSolidReactor(MECH, isothermal=True, **FAST)
    res = reactor.run(t_end=2000.0)
    assert res.burned_out
    np.testing.assert_allclose(res.T, FAST["T0"], atol=1e-9)


def test_nonisothermal_temperature_rises(burnout_result):
    # Char oxidation + CO burnout are exothermic; adiabatic T must rise.
    assert burnout_result.T[-1] > burnout_result.T[0] + 100.0


def test_isothermal_burnout_slower_than_adiabatic(burnout_result):
    """Self-heating accelerates Arrhenius kinetics — a physics sanity check."""
    reactor = FiniteSolidReactor(MECH, isothermal=True, **FAST)
    res_iso = reactor.run(t_end=2000.0)
    assert res_iso.burned_out
    assert res_iso.burnout_time > burnout_result.burnout_time


# ---------------------------------------------------------------------------
# Pluggable area model
# ---------------------------------------------------------------------------
def test_constant_area_model():
    reactor = FiniteSolidReactor(MECH, area_model=constant_area,
                                 isothermal=True, **FAST)
    res = reactor.run(t_end=2000.0)
    assert res.burned_out
    # Area stays at A0 until (near) exhaustion.
    assert np.all(res.area[:-1] == res.area[0])


# ---------------------------------------------------------------------------
# Phase auto-detection + guardrails
# ---------------------------------------------------------------------------
def test_phase_autodetection():
    r = FiniteSolidReactor(MECH, **FAST)
    assert r.gas.name == "gas"
    assert r.surf.name == "char_surface"
    assert r.bulk.name == "char"


def test_explicit_phase_names():
    r = FiniteSolidReactor(MECH, gas_phase="gas",
                           surface_phase="char_surface", bulk_phase="char",
                           **FAST)
    assert r.bulk.name == "char"


def test_oxygen_starvation_stops_cleanly():
    """A tiny gas volume runs out of O2 — reactor must not go negative or
    fabricate mass, just stall with the solid partially consumed."""
    reactor = FiniteSolidReactor(MECH, T0=1600.0, bulk_mass_kg=1.0e-4,
                                 gas_volume_m3=1.0e-6, isothermal=True)
    res = reactor.run(t_end=50.0)
    assert not res.burned_out                    # not enough O2 to finish
    assert res.m_bulk[-1] > 0.5 * res.m_bulk[0]  # most solid remains
    assert res.audit["max_element_drift_rel"] < 1.0e-8
    i_o2 = res.gas_species.index("O2")
    assert res.gas_mass[-1, i_o2] >= 0.0
    assert res.gas_mass[-1, i_o2] < 0.05 * res.gas_mass[0, i_o2]


def test_csv_roundtrip(tmp_path, burnout_result):
    out = tmp_path / "traj.csv"
    burnout_result.to_csv(out)
    data = np.genfromtxt(out, delimiter=",", names=True)
    assert len(data) == len(burnout_result.t)
    np.testing.assert_allclose(data["m_bulk_kg"], burnout_result.m_bulk)
