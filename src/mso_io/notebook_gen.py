"""notebook_gen.py -- Jupyter notebook (.ipynb) template generation.

KRUNAL_JULY_23.md point 8: "what about ... jUPYTER NOTEBOOKS ... ADD THOSE
ALSO" -- no backend existed anywhere in this repo for generating a .ipynb.

Deliberately dependency-free (writes the nbformat-v4 JSON schema by hand,
stdlib `json` only) rather than depending on the `nbformat` package: it's
present in the anaconda env but NOT in the PySide6 `.venv-gui` env, and per
this repo's isolation policy new deps don't get pip-installed into the
shared anaconda env just to satisfy one small feature -- writing the (very
small, stable) schema directly means this module works unmodified from
either interpreter, no bridging needed.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


def new_notebook(kernel_name: str = "python3", language: str = "python") -> Dict[str, Any]:
    return {
        "cells": [],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3", "language": language, "name": kernel_name,
            },
            "language_info": {"name": language},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def _split_source(text: str) -> List[str]:
    """nbformat stores multi-line source as a list of lines, each keeping
    its own trailing newline except the last."""
    lines = text.splitlines(keepends=True)
    return lines if lines else [""]


def add_markdown_cell(nb: Dict[str, Any], text: str) -> None:
    nb["cells"].append({
        "cell_type": "markdown", "metadata": {}, "source": _split_source(text),
    })


def add_code_cell(nb: Dict[str, Any], source: str) -> None:
    nb["cells"].append({
        "cell_type": "code", "execution_count": None, "metadata": {},
        "outputs": [], "source": _split_source(source),
    })


def save_notebook(nb: Dict[str, Any], path: str) -> str:
    with open(path, "w") as fh:
        json.dump(nb, fh, indent=1)
        fh.write("\n")
    return path


@dataclass
class NotebookRequest:
    """Options for build_mechanism_notebook()."""
    mechanism_path: str
    kind: str = "idt"          # "idt" | "flame_speed" | "load_only"
    fuel: str = "H2"
    oxidizer: str = "O2:1.0, N2:3.76"
    T_K: float = 1000.0
    P_atm: float = 1.0
    phi: float = 1.0
    title: str = ""
    extra_notes: str = ""


_KIND_LABELS = {"idt": "ignition delay", "flame_speed": "laminar flame speed",
                "load_only": "mechanism load + inspection"}


def build_mechanism_notebook(req: NotebookRequest) -> Dict[str, Any]:
    """A ready-to-run "load mechanism, run sim, plot" template notebook
    against this repo's Cantera-based tooling."""
    nb = new_notebook()
    title = req.title or f"{_KIND_LABELS.get(req.kind, req.kind).title()} — {req.mechanism_path}"
    add_markdown_cell(nb, f"# {title}\n\nGenerated by `mso_io.notebook_gen` "
                           f"(KRUNAL_JULY_23.md point 8).")
    if req.extra_notes:
        add_markdown_cell(nb, req.extra_notes)

    add_markdown_cell(nb, "## Load mechanism")
    add_code_cell(nb, (
        "import cantera as ct\n"
        "import numpy as np\n"
        "import matplotlib.pyplot as plt\n\n"
        f"mechanism_path = {req.mechanism_path!r}\n"
        "gas = ct.Solution(mechanism_path)\n"
        f"gas.TP = {req.T_K}, {req.P_atm} * ct.one_atm\n"
        f"gas.set_equivalence_ratio({req.phi}, {req.fuel!r}, {req.oxidizer!r})\n"
        "print(f'{gas.n_species} species, {gas.n_reactions} reactions')"
    ))

    if req.kind == "idt":
        add_markdown_cell(nb, "## Run: constant-volume ignition delay")
        add_code_cell(nb, (
            "reactor = ct.IdealGasReactor(gas)\n"
            "sim = ct.ReactorNet([reactor])\n"
            "t_end = 1.0  # s -- adjust if ignition hasn't occurred by here\n"
            "times, temperatures = [], []\n"
            "t = 0.0\n"
            "while t < t_end:\n"
            "    t = sim.step()\n"
            "    times.append(t)\n"
            "    temperatures.append(reactor.T)\n"
            "    if t > t_end:\n"
            "        break\n"
            "times = np.array(times)\n"
            "temperatures = np.array(temperatures)\n"
            "dTdt = np.gradient(temperatures, times)\n"
            "idt = times[np.argmax(dTdt)]\n"
            "print(f'IDT (max dT/dt) = {idt:.6e} s')"
        ))
        add_markdown_cell(nb, "## Plot")
        add_code_cell(nb, (
            "fig, ax = plt.subplots(figsize=(7, 4))\n"
            "ax.plot(times, temperatures)\n"
            "ax.axvline(idt, color='r', ls='--', label=f'IDT = {idt:.3e} s')\n"
            "ax.set_xlabel('Time [s]'); ax.set_ylabel('Temperature [K]')\n"
            "ax.legend(); fig.tight_layout()\n"
            "plt.show()"
        ))
    elif req.kind == "flame_speed":
        add_markdown_cell(nb, "## Run: freely-propagating flame")
        add_code_cell(nb, (
            "width = 0.03  # m\n"
            "flame = ct.FreeFlame(gas, width=width)\n"
            "flame.set_refine_criteria(ratio=3, slope=0.06, curve=0.12)\n"
            "flame.solve(loglevel=0, auto=True)\n"
            "print(f'Laminar flame speed = {flame.velocity[0]:.4f} m/s')"
        ))
        add_markdown_cell(nb, "## Plot")
        add_code_cell(nb, (
            "fig, ax = plt.subplots(figsize=(7, 4))\n"
            "ax.plot(flame.grid * 1e3, flame.T)\n"
            "ax.set_xlabel('Position [mm]'); ax.set_ylabel('Temperature [K]')\n"
            "fig.tight_layout(); plt.show()"
        ))
    else:
        add_markdown_cell(nb, "## Inspect")
        add_code_cell(nb, (
            "for sp in gas.species_names[:20]:\n"
            "    print(sp)\n"
            "print('...' if gas.n_species > 20 else '')"
        ))

    return nb


def generate_mechanism_notebook(out_path: str, req: NotebookRequest) -> str:
    nb = build_mechanism_notebook(req)
    return save_notebook(nb, out_path)
