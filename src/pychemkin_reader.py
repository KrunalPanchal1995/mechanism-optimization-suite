"""
pychemkin_reader.py
-------------------
Thin adapter around PyChemkin's ckcsv output readers.

This module does NOT require a Chemkin Pro license.  It reads existing
Chemkin Pro ckcsv output files (already generated by the user) and
exposes the data as numpy arrays or plain dicts.

All heavy subprocess / license logic in the original PyChemkin-master is
intentionally excluded — only the data-extraction functions are imported.

Usage::

    from pychemkin_reader import CKCSVReader

    rdr = CKCSVReader("simulation.ckcsv")
    print(rdr.list_variables())

    time, T = rdr.get_variable("Temperature_K")
    idt      = rdr.get_ignition_delay(species=["OH"])
    df       = rdr.to_dataframe()
"""

from __future__ import annotations

import os
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# Resolve PyChemkin path
# ---------------------------------------------------------------------------

_HERE = Path(__file__).parent.parent          # /data/OPEN_CODE/PHASE-3
_PYCHEMKIN_DIR = _HERE / "PyChemkin-master"

if str(_PYCHEMKIN_DIR) not in sys.path and _PYCHEMKIN_DIR.is_dir():
    sys.path.insert(0, str(_PYCHEMKIN_DIR))

try:
    from chemkin import getVariable, getMoleFraction, getIgnitionDelay, getTotalMoles
    _PYCHEMKIN_OK = True
except ImportError:
    _PYCHEMKIN_OK = False


class CKCSVReader:
    """
    Read variables from a Chemkin Pro .ckcsv output file.

    Parameters
    ----------
    ckcsv_path : str | Path
        Path to the ckcsv output file.
    """

    def __init__(self, ckcsv_path: str | Path):
        self.path = str(ckcsv_path)
        if not os.path.exists(self.path):
            raise FileNotFoundError(f"ckcsv file not found: {self.path}")

    # ------------------------------------------------------------------

    def list_variables(self) -> List[str]:
        """Return all variable names present in the ckcsv file."""
        if not _PYCHEMKIN_OK:
            return self._list_variables_fallback()
        raw = getVariable(self.path)   # returns dict when variable=None
        if isinstance(raw, dict):
            return sorted(raw.keys())
        return []

    def get_variable(self, variable: str) -> Tuple[np.ndarray, np.ndarray]:
        """
        Return (time, values) arrays for *variable*.

        If the file has no explicit time column, time is a sequential index.
        """
        if not _PYCHEMKIN_OK:
            return self._get_variable_fallback(variable)
        data = getVariable(self.path, variable=variable)
        if isinstance(data, dict):
            t_key = next((k for k in data if "time" in k.lower()), None)
            t = np.array(data.get(t_key, list(range(len(next(iter(data.values())))))),
                         dtype=float)
            v = np.array(data.get(variable, []), dtype=float)
        else:
            t = np.arange(len(data), dtype=float)
            v = np.array(data, dtype=float)
        return t, v

    def get_mole_fractions(self, species: List[str]) -> Dict[str, np.ndarray]:
        """Return mole-fraction arrays for the given species list."""
        if not _PYCHEMKIN_OK:
            return {}
        raw = getMoleFraction(self.path, species=species)
        return {k: np.array(v, dtype=float) for k, v in raw.items()}

    def get_ignition_delay(
        self,
        tol: float = 1.0,
        species: Optional[List[str]] = None,
        cond: str = "onset",
    ) -> float:
        """
        Compute ignition delay time [s] from the ckcsv file.

        Parameters
        ----------
        tol     : temperature rise tolerance (K) — passed to PyChemkin
        species : optional list of species for radical-peak criterion
        cond    : 'onset' (default) or 'peak'
        """
        if not _PYCHEMKIN_OK:
            return float("nan")
        return getIgnitionDelay(self.path, tol=tol,
                                species=species or [], cond=cond)

    def get_total_moles(self) -> np.ndarray:
        """Return total moles array over time."""
        if not _PYCHEMKIN_OK:
            return np.array([])
        return np.array(getTotalMoles(self.path), dtype=float)

    def to_dataframe(self):
        """Return all data as a pandas DataFrame (requires pandas)."""
        import pandas as pd
        all_data = {}
        for varname in self.list_variables():
            try:
                _, v = self.get_variable(varname)
                all_data[varname] = v
            except Exception:
                continue
        # Align lengths (take shortest)
        min_len = min(len(v) for v in all_data.values()) if all_data else 0
        return pd.DataFrame({k: v[:min_len] for k, v in all_data.items()})

    # ------------------------------------------------------------------
    # Fallback CSV reader (no PyChemkin dependency)
    # ------------------------------------------------------------------

    def _parse_raw(self) -> Dict[str, list]:
        """Parse ckcsv into a dict of lists without PyChemkin."""
        cols: Dict[str, list] = {}
        with open(self.path, "r", encoding="utf-8", errors="replace") as fh:
            lines = fh.readlines()
        if not lines:
            return cols
        # ckcsv: first row is variable names, subsequent rows are data
        # Some ckcsv files have two header rows (name + units)
        header = [h.strip().strip('"') for h in lines[0].split(",")]
        data_start = 1
        if len(lines) > 1:
            try:
                float(lines[1].split(",")[0])
            except ValueError:
                data_start = 2   # second row is units
        for name in header:
            cols[name] = []
        for line in lines[data_start:]:
            parts = line.split(",")
            for i, name in enumerate(header):
                try:
                    cols[name].append(float(parts[i]) if i < len(parts) else float("nan"))
                except (ValueError, IndexError):
                    cols[name].append(float("nan"))
        return cols

    def _list_variables_fallback(self) -> List[str]:
        return sorted(self._parse_raw().keys())

    def _get_variable_fallback(self, variable: str):
        raw = self._parse_raw()
        t_key = next((k for k in raw if "time" in k.lower()), None)
        t = np.array(raw.get(t_key, list(range(len(raw.get(variable, []))))), dtype=float)
        v = np.array(raw.get(variable, []), dtype=float)
        return t, v


# ---------------------------------------------------------------------------
# Tkinter GUI panel — embeddable in the main GUI
# ---------------------------------------------------------------------------

try:
    import tkinter as tk
    from tkinter import filedialog, messagebox, ttk
    _TK_OK = True
except ImportError:
    _TK_OK = False


class CKCSVViewerPanel(ttk.Frame if _TK_OK else object):
    """
    Tkinter panel to browse, inspect, and plot data from a Chemkin Pro ckcsv file.

    Usage::

        panel = CKCSVViewerPanel(parent, palette=PALETTE)
        panel.pack(fill=tk.BOTH, expand=True)
    """

    def __init__(self, parent, palette: Optional[dict] = None):
        if not _TK_OK:
            raise RuntimeError("tkinter not available")
        super().__init__(parent)
        self._pal = palette or {"bg": "#1e1e2e", "surface": "#2a2a3e",
                                "accent": "#7aa2f7", "text": "#cdd6f4"}
        self._reader: Optional[CKCSVReader] = None
        self._build_ui()

    def _build_ui(self):
        self.configure(padding=6)

        # ── toolbar ──────────────────────────────────────────────────
        top = ttk.Frame(self)
        top.pack(fill=tk.X, pady=(0, 4))
        self._path_var = tk.StringVar(value="No file loaded")
        ttk.Label(top, textvariable=self._path_var, width=55, anchor=tk.W).pack(side=tk.LEFT)
        ttk.Button(top, text="Open ckcsv…",      command=self._open_ckcsv).pack(side=tk.LEFT, padx=4)
        ttk.Button(top, text="Show IDT",         command=self._show_idt).pack(side=tk.LEFT, padx=2)
        ttk.Button(top, text="Plot variable…",   command=self._plot_variable).pack(side=tk.LEFT, padx=2)
        ttk.Button(top, text="Export CSV…",      command=self._export_csv).pack(side=tk.LEFT, padx=2)

        # ── variable list + preview ───────────────────────────────────
        pane = ttk.PanedWindow(self, orient=tk.HORIZONTAL)
        pane.pack(fill=tk.BOTH, expand=True)

        var_frame = ttk.LabelFrame(pane, text="Variables", padding=4)
        pane.add(var_frame, weight=1)
        vbar = tk.Scrollbar(var_frame)
        vbar.pack(side=tk.RIGHT, fill=tk.Y)
        self._var_list = tk.Listbox(
            var_frame, yscrollcommand=vbar.set, exportselection=False,
            bg=self._pal["surface"], fg=self._pal["text"],
            selectbackground=self._pal["accent"], font=("DejaVu Sans Mono", 8),
        )
        self._var_list.pack(fill=tk.BOTH, expand=True)
        vbar.config(command=self._var_list.yview)

        prev_frame = ttk.LabelFrame(pane, text="Data preview", padding=4)
        pane.add(prev_frame, weight=3)
        pbar = tk.Scrollbar(prev_frame)
        pbar.pack(side=tk.RIGHT, fill=tk.Y)
        self._preview = tk.Text(
            prev_frame, yscrollcommand=pbar.set, wrap=tk.NONE,
            font=("DejaVu Sans Mono", 8),
            bg=self._pal["surface"], fg=self._pal["text"],
            relief=tk.FLAT, state=tk.DISABLED,
        )
        self._preview.pack(fill=tk.BOTH, expand=True)
        pbar.config(command=self._preview.yview)
        self._var_list.bind("<<ListboxSelect>>", self._on_select)

        self._status = tk.StringVar(value="Open a ckcsv file to begin.")
        ttk.Label(self, textvariable=self._status, anchor=tk.W).pack(fill=tk.X)

    # ------------------------------------------------------------------

    def _open_ckcsv(self):
        path = filedialog.askopenfilename(
            filetypes=[("Chemkin CSV", "*.ckcsv *.csv"), ("All", "*")],
            title="Open Chemkin Pro ckcsv file",
        )
        if not path:
            return
        try:
            self._reader = CKCSVReader(path)
            self._path_var.set(os.path.basename(path))
            vars_ = self._reader.list_variables()
            self._var_list.delete(0, tk.END)
            for v in vars_:
                self._var_list.insert(tk.END, v)
            self._status.set(f"Loaded — {len(vars_)} variables.")
        except Exception as exc:
            messagebox.showerror("Error", str(exc))

    def _on_select(self, _event):
        if self._reader is None:
            return
        sel = self._var_list.curselection()
        if not sel:
            return
        var = self._var_list.get(sel[0])
        try:
            t, v = self._reader.get_variable(var)
            self._show_preview(var, t, v)
        except Exception as exc:
            self._status.set(f"Error: {exc}")

    def _show_preview(self, varname: str, t: np.ndarray, v: np.ndarray):
        self._preview.config(state=tk.NORMAL)
        self._preview.delete("1.0", tk.END)
        self._preview.insert(tk.END, f"Variable: {varname}\n")
        self._preview.insert(tk.END, f"Points: {len(v)}\n\n")
        self._preview.insert(tk.END, f"{'Index':>6}  {'Time':>14}  {'Value':>14}\n")
        self._preview.insert(tk.END, "-" * 40 + "\n")
        for i in range(min(len(v), 50)):
            self._preview.insert(tk.END, f"{i:>6}  {t[i] if i < len(t) else '':>14.6g}  {v[i]:>14.6g}\n")
        if len(v) > 50:
            self._preview.insert(tk.END, f"  … ({len(v)} total rows)\n")
        self._preview.config(state=tk.DISABLED)

    def _show_idt(self):
        if self._reader is None:
            messagebox.showinfo("No file", "Load a ckcsv file first.")
            return
        try:
            idt = self._reader.get_ignition_delay()
            messagebox.showinfo("Ignition Delay", f"IDT = {idt:.6g} s  ({idt*1000:.4g} ms)")
        except Exception as exc:
            messagebox.showerror("IDT error", str(exc))

    def _plot_variable(self):
        if self._reader is None:
            messagebox.showinfo("No file", "Load a ckcsv file first.")
            return
        sel = self._var_list.curselection()
        if not sel:
            messagebox.showinfo("No selection", "Select a variable from the list.")
            return
        var = self._var_list.get(sel[0])
        try:
            import matplotlib.pyplot as plt
            t, v = self._reader.get_variable(var)
            fig, ax = plt.subplots()
            ax.plot(t, v)
            ax.set_xlabel("Time (or index)")
            ax.set_ylabel(var)
            ax.set_title(f"{os.path.basename(self._reader.path)} — {var}")
            plt.tight_layout()
            plt.show()
        except ImportError:
            messagebox.showinfo("matplotlib required",
                                "Install matplotlib to plot:\n  pip install matplotlib")
        except Exception as exc:
            messagebox.showerror("Plot error", str(exc))

    def _export_csv(self):
        if self._reader is None:
            messagebox.showinfo("No file", "Load a ckcsv file first.")
            return
        path = filedialog.asksaveasfilename(
            defaultextension=".csv",
            filetypes=[("CSV", "*.csv"), ("All", "*")],
            title="Export data as CSV",
        )
        if not path:
            return
        try:
            import csv
            vars_ = self._reader.list_variables()
            arrays = {}
            for var in vars_:
                try:
                    _, v = self._reader.get_variable(var)
                    arrays[var] = v
                except Exception:
                    continue
            if not arrays:
                messagebox.showinfo("Empty", "No data to export.")
                return
            n = max(len(v) for v in arrays.values())
            with open(path, "w", newline="") as fh:
                wr = csv.writer(fh)
                wr.writerow(list(arrays.keys()))
                for i in range(n):
                    row = []
                    for v in arrays.values():
                        row.append(v[i] if i < len(v) else "")
                    wr.writerow(row)
            messagebox.showinfo("Exported", f"Saved to:\n{path}")
        except Exception as exc:
            messagebox.showerror("Export error", str(exc))
