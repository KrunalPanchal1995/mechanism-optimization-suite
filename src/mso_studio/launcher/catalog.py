CATALOG_BY_ID = {entry.id: entry for entry in CATALOG}


def script_path(entry: AppEntry) -> Path:
    """Absolute path to *entry*'s script, resolved against the repo root."""
    return REPO_ROOT / entry.script


def entries_for_stage(stage: str) -> List[AppEntry]:
    return [e for e in CATALOG if e.stage == stage]


def search(query: str) -> List[AppEntry]:
    """Case-insensitive substring match against title/tagline/description."""
    q = query.strip().lower()
    if not q:
        return list(CATALOG)
    return [
        e for e in CATALOG
        if q in e.title.lower() or q in e.tagline.lower() or q in e.description.lower()
    ]
