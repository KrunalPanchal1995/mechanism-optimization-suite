"""
mso_studio.launcher.catalog
==============================
Single source of truth for what the launcher can start. Pure Python, no Qt --
importable from the anaconda interpreter too (see the note in
``launcher/__init__.py``).

This is now genuinely the *only* place these apps are listed:
``launcher_gui.py``'s Tkinter ``_APPS`` list is generated by filtering this
``CATALOG`` for ``RUNNER_SCIENCE`` entries (Session A4 of the visual-system
plan inverted the original direction, where ``_APPS`` was hand-maintained
and this file was merely checked against it for drift). Adding a new
science-tool entry here makes it appear in both launchers automatically;
there is nothing left to keep in sync by hand.

**Phase 1 of the 2026-08 GUI integration overhaul**: every entry with a
PySide6 module-page equivalent now launches ``run_mso_studio.py --module
<id> --standalone`` (``RUNNER_GUI_VENV``) instead of its old standalone
Tkinter script -- clicking a tile now opens the real PySide6 page, not the
legacy GUI of the same name. ``launcher_gui.py``'s Tkinter fallback (used
only when ``.venv-gui`` doesn't exist yet) necessarily shrinks to just the
handful of entries that have no PySide6 page yet -- that's expected, not a
regression, since PySide6 is a hard requirement for those entries either
way now.
"""
